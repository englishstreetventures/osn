#!/usr/bin/env bun
/**
 * Write cire's baseline, `cire/db/migrations/0001_initial.sql`, from a replay
 * of the chain it stands for: `cire/db/migrations-archive/long-lived/`, the
 * previous baseline and every migration a squash moved out after it.
 *
 * The chain is replayed into `bun:sqlite` with `PRAGMA foreign_keys = ON`, as
 * D1 enforces them. Each table's, view's, index's and trigger's SQL, as SQLite
 * stored it in `sqlite_master` (never a `sqlite_%` object), becomes one
 * statement: tables, then views, then indexes, then triggers, each kind in
 * creation (`rowid`) order, each statement ended by `;` and separated from the
 * next by `--> statement-breakpoint`. So the baseline keeps the column order
 * and index names a deployed database has, and
 * `cire/api/tests/db/ddl-lockstep.test.ts` holds it to building exactly what
 * the chain builds. The squash method is in `cire/db/README.md`.
 *
 * Usage, from the repository root: `bun run scripts/cire-db-baseline.ts`.
 * Writes the file; reads nothing else.
 *
 * Imports nothing but Node built-ins, `bun:sqlite` and a sibling script.
 */

import { Database } from "bun:sqlite";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

import { listMigrations, migrationStatements } from "./migration-files";

const REPO_ROOT = resolve(import.meta.dir, "..");
export const LONG_LIVED_DIR = resolve(REPO_ROOT, "cire/db/migrations-archive/long-lived");
export const BASELINE_PATH = resolve(REPO_ROOT, "cire/db/migrations/0001_initial.sql");

const HEADER = `-- 0001_initial.sql — the cire D1 BASELINE.
--
-- This one file creates the whole schema. It builds exactly what the chain in
-- ../migrations-archive/long-lived/ builds when replayed in name order (the
-- previous baseline, then every migration after it), object for object and
-- byte for byte; cire/api/tests/db/ddl-lockstep.test.ts holds it to that.
--
-- WHY ONE FILE: D1 bills a from-zero build per schema statement. This file
-- spends one CREATE per table, index and trigger.
-- scripts/guard-d1-migration-cost.ts prices it against the free-tier ceiling.
--
-- WHO RUNS IT: a new database only — a local one, through
-- \`bun run --cwd cire/db db:migrate:local\`, or an investigation stage's.
-- Dev and production never do: their ledgers recorded the previous baseline
-- under this name, so the cire stack hands them the long-lived chain instead
-- (CIRE_DB_LONG_LIVED_MIGRATIONS, cire/infra/src/declaration.ts).
--
-- KEEP THE FILENAME. \`wrangler d1 migrations apply\` skips any file already
-- named in the database's \`d1_migrations\` ledger, and every local database
-- built from an earlier chain holds \`0001_initial.sql\`, so wrangler skips this
-- file there and applies only what comes after it. scripts/cire-db-migrate.ts
-- reads the ledger first and refuses a database that stopped part-way through
-- an archived chain.
--
-- GENERATED by scripts/cire-db-baseline.ts from a replay of the long-lived
-- chain; never edit it by hand. Each statement is the SQL SQLite stored for
-- that table, index or trigger once the chain had run (sqlite_master): tables
-- first, then indexes, then triggers, each in creation order. So the column
-- ORDER is the order production has (ALTER TABLE ... ADD can only append, so
-- it differs from schema.ts) and every index keeps its real name.
--
-- New migrations are timestamped and applied after this file, in name order.
`;

/** One heading per kind of object, in the order the baseline creates them. */
const KINDS = [
  { type: "table", heading: "Tables" },
  { type: "view", heading: "Views" },
  { type: "index", heading: "Indexes" },
  { type: "trigger", heading: "Triggers" },
] as const;

const heading = (title: string): string => `-- ── ${title} ${"─".repeat(71 - title.length)}`;

/** The baseline's text for the chain in `dir`. */
export function baselineSql(dir: string = LONG_LIVED_DIR): string {
  const db = new Database(":memory:");
  try {
    db.exec("PRAGMA foreign_keys = ON;");
    for (const file of listMigrations(dir)) {
      for (const statement of migrationStatements(readFileSync(join(dir, file), "utf8"))) {
        db.exec(statement);
      }
    }
    const objects = db
      .query(
        "SELECT type, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid",
      )
      .all() as Array<{ type: string; sql: string }>;
    const chunks = KINDS.flatMap(({ type, heading: title }) =>
      objects
        .filter((object) => object.type === type)
        .map((object, index) => `${index === 0 ? `${heading(title)}\n` : ""}${object.sql};`),
    );
    return `${HEADER}\n${chunks.join("\n--> statement-breakpoint\n")}\n`;
  } finally {
    db.close();
  }
}

if (import.meta.main) {
  writeFileSync(BASELINE_PATH, baselineSql());
  process.stdout.write(`cire-db-baseline: wrote ${BASELINE_PATH}\n`);
}
