/**
 * The closed set of coordination store names. Each one is a namespace on the
 * `COORDINATION` Durable Object binding (objects are named `<store>:<key>`)
 * and the `store` attribute on its metric and log line, so a store that is not
 * listed here cannot be built, measured or logged. A key, an IP, an account or
 * a stored value is never a store name.
 *
 * Names match `/^[A-Za-z0-9_.-]{1,64}$/`, the namespace rule in
 * `@shared/coordination`; `:` separates the name from the key, so it never
 * appears in one.
 */

import type { AuthLimiterStoreName, OsnLimiterStoreName } from "../../routes/auth/limiters";

/** Short-lived ceremony state: challenges, pending codes, parked requests. */
export type CeremonyStoreName =
  | "reg_challenge"
  | "login_challenge"
  | "pending_registration"
  | "step_up_challenge"
  | "step_up_otp"
  | "pending_email_change"
  | "cross_device"
  // The TOTP secret generated by /totp/enroll/begin and not yet confirmed. It
  // is never written to the database, since an unconfirmed secret is not a credential.
  | "pending_totp_enroll"
  // The 6-digit code emailed by /login/recovery/email/begin. Never in D1 — a
  // pending recovery code is not a credential.
  | "pending_recovery_otp"
  // The single-use "this wasn't me" token carried by the recovery notice
  // email, holding only the SHA-256 of its secret half. Never in D1.
  | "recovery_disown"
  // OIDC: validated /authorize requests parked while the consent UI runs.
  | "oidc_authorize_request";

/** Per-account failed-attempt counters. Three, so no factor can lock out another. */
export type LockoutStoreName = "recovery_lockout" | "recovery_otp_lockout" | "totp_lockout";

export type CoordinationStoreName =
  | CeremonyStoreName
  | LockoutStoreName
  // Consumed step-up token ids: a token verifies once.
  | "step_up_jti"
  // `GET /health/coordination`'s round trip: one fresh server-made key per
  // probe, removed before it answers.
  | "health_probe"
  | AuthLimiterStoreName
  | OsnLimiterStoreName;

/** Where a store's state lives: this process, or the shared Durable Object. */
export type CoordinationBackend = "memory" | "durable_object";
