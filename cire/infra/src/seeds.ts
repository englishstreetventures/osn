import { Data } from "effect";

export class SeedInputError extends Data.TaggedError("SeedInputError")<{
  /** Which input was refused, by the name of the variable it comes from. Never its content. */
  readonly input: string;
  readonly message: string;
}> {}

/** A profile id: `usr_` and URL-safe base64. Nothing else reaches the SQL. */
const PROFILE_ID = /^usr_[A-Za-z0-9_-]+$/;

/** The sample wedding's owner seat in `cire/db/seed/dev-seed.sql`, whose id never changes. */
const OWNER_SEAT_ID = "whost_d1f0c4a2-0000-4000-8000-000000000000";

/**
 * The SQL that gives the seeded sample wedding to the account
 * `CIRE_DEV_OWNER_PROFILE_ID` names, as `scripts/cire-db-seed.sh` does: any
 * other seat that profile holds on the wedding goes first, since a profile
 * holds one seat per wedding, then the owner seat takes the profile. Alchemy
 * imports it after the dev seed.
 *
 * Unset or empty (an unset GitHub variable reaches the step as `""`) gives
 * null: the wedding stays with the seed's placeholder owner and the stack
 * writes no file. Any other value must be a profile id, which carries no
 * quote, so it is safe inside a SQL string literal. The file holds nothing
 * that changes between runs.
 */
export function ownerSeatSql(profileId: string | undefined): string | null {
  if (profileId === undefined || profileId === "") return null;
  if (!PROFILE_ID.test(profileId)) {
    // The value can carry SQL, so the message never repeats it.
    throw new SeedInputError({
      input: "CIRE_DEV_OWNER_PROFILE_ID",
      message:
        "CIRE_DEV_OWNER_PROFILE_ID is not a profile id: it must be usr_ followed by letters, digits, - or _.",
    });
  }
  return `-- Generated by cire/infra on every deploy; Alchemy re-imports it when it changes.
DELETE FROM wedding_hosts WHERE wedding_id='wed_bootstrap' AND osn_profile_id='${profileId}' AND id<>'${OWNER_SEAT_ID}';
UPDATE wedding_hosts SET osn_profile_id='${profileId}', added_by_osn_profile_id='${profileId}', role='owner' WHERE id='${OWNER_SEAT_ID}';
`;
}
